"""
Slices the Alimama FangYuanTi variable font into small WOFF2 files for the docs site.

Use when:
- the CJK title font changes, or the Chinese docs gained characters that should load in the first chunk

Expects:
- Python 3 with `fonttools` and `brotli` installed (`pip install fonttools brotli`)
- the source TTF path as the first argument; the 7 MB source font is not committed

Writes:
- docs/content/public/fonts/alimama-fangyuanti/*.woff2
- docs/.vitepress/theme/fonts/alimamaFangYuanTi.css with one `@font-face` per chunk

Run from the repository root:
  python3 docs/scripts/subsetCjkFont.py ~/Downloads/AliMaMaSquareRound.ttf
"""

import io
import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT_DIR = ROOT / 'docs/content/public/fonts/alimama-fangyuanti'
CSS_PATH = ROOT / 'docs/.vitepress/theme/fonts/alimamaFangYuanTi.css'
DOCS_DIR = ROOT / 'docs/content/zh-hans'

FAMILY = 'Alimama FangYuanTi'
# NOTICE: The "Bold" named instance of the variable font. BEVL controls corner rounding:
# 1 = "Bold-Square", 80 = "Bold", 100 = "Bold-Round".
INSTANCE = {'wght': 700, 'BEVL': 80}
# Characters per fallback chunk. Smaller chunks download less per new character but add requests.
CHUNK_SIZE = 300


def is_cjk(codepoint: int) -> bool:
  return (
    0x3000 <= codepoint <= 0x303F  # CJK symbols and punctuation
    or 0x4E00 <= codepoint <= 0x9FFF  # CJK unified ideographs
    or 0xFF00 <= codepoint <= 0xFFEF  # Full-width forms
  )


def unicode_range(codepoints: list[int]) -> str:
  """
  Normalizes sorted codepoints into a CSS `unicode-range` value.

  Before:
  - [0x4E00, 0x4E01, 0x4E03]

  After:
  - "U+4E00-4E01, U+4E03"
  """
  ranges: list[str] = []
  start = previous = codepoints[0]
  for codepoint in codepoints[1:] + [None]:
    if codepoint is not None and codepoint == previous + 1:
      previous = codepoint
      continue
    ranges.append(f'U+{start:X}' if start == previous else f'U+{start:X}-{previous:X}')
    if codepoint is not None:
      start = previous = codepoint
  return ', '.join(ranges)


def main() -> None:
  source = pathlib.Path(sys.argv[1]).expanduser()
  font = instancer.instantiateVariableFont(TTFont(source), INSTANCE)
  available = {codepoint for codepoint in font.getBestCmap() if is_cjk(codepoint)}

  # Subsetting mutates the font, so keep the static instance as bytes and load a fresh copy per chunk.
  instance = io.BytesIO()
  font.save(instance)

  # The first chunk holds every CJK character the Chinese docs use today, so most pages load one file.
  used = {ord(char) for path in DOCS_DIR.rglob('*.md') for char in path.read_text('utf-8')}
  first = sorted(available & used)
  rest = sorted(available - used)
  chunks = [first] + [rest[index:index + CHUNK_SIZE] for index in range(0, len(rest), CHUNK_SIZE)]

  OUT_DIR.mkdir(parents=True, exist_ok=True)
  for stale in OUT_DIR.glob('*.woff2'):
    stale.unlink()

  faces: list[str] = []
  for index, codepoints in enumerate(chunks):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    instance.seek(0)
    chunk = TTFont(instance)
    subsetter.subset(chunk)
    name = f'{index:02d}.woff2'
    chunk.flavor = 'woff2'
    chunk.save(OUT_DIR / name)
    faces.append(
      '@font-face {\n'
      f"  font-family: '{FAMILY}';\n"
      '  font-style: normal;\n'
      '  font-weight: 700;\n'
      '  font-display: swap;\n'
      f"  src: url('/fonts/alimama-fangyuanti/{name}') format('woff2');\n"
      f'  unicode-range: {unicode_range(codepoints)};\n'
      '}\n'
    )

  CSS_PATH.parent.mkdir(parents=True, exist_ok=True)
  CSS_PATH.write_text(
    '/* Generated by docs/scripts/subsetCjkFont.py from Alimama FangYuanTi (Bold). Do not edit by hand. */\n\n'
    + '\n'.join(faces),
    'utf-8',
  )
  print(f'{len(chunks)} chunks, first chunk {len(first)} characters')


if __name__ == '__main__':
  main()
